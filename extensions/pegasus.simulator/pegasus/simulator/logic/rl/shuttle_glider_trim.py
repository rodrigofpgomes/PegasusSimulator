# Thrust reserve on every lift rotor at reset [N]: none, the table uses the actuator limits only
TRIM_ROTOR_RESERVE = 0.0
# Admissible negative lift thrust of the closed-form balance [N] (a rotor stopped at its lower limit; clamped to zero)
TRIM_THRUST_TOLERANCE = 0.3


def interpolate_table(speed: torch.Tensor, values) -> torch.Tensor:
    """Piecewise-linear interpolation of a trim column in airspeed, clamped to the table range."""
    knots = torch.tensor(TRIM_SPEED_KNOTS, dtype=speed.dtype, device=speed.device)
    table = torch.tensor(values, dtype=speed.dtype, device=speed.device)
    v = speed.clamp(min=knots[0], max=knots[-1])
    upper = torch.bucketize(v, knots).clamp(1, knots.numel() - 1)
    lower = upper - 1
    blend = (v - knots[lower]) / (knots[upper] - knots[lower]).clamp_min(1e-6)
    return table[lower] + blend * (table[upper] - table[lower])


def trim_attitude(heading: torch.Tensor, alpha: torch.Tensor, bank: torch.Tensor) -> torch.Tensor:
    """Body-to-world rotation (FLU/ENU) R = Rz(heading) Rx(bank) Ry(-alpha): nose up by alpha above the horizontal
    velocity, then banked about the velocity. Negative bank lowers the left wing."""
    n = heading.shape[0]
    z, o = torch.zeros_like(heading), torch.ones_like(heading)
    cy, sy = torch.cos(heading), torch.sin(heading)
    cb, sb = torch.cos(bank), torch.sin(bank)
    ca, sa = torch.cos(alpha), torch.sin(alpha)
    Rz = torch.stack((cy, -sy, z, sy, cy, z, z, z, o), dim=1).reshape(n, 3, 3)
    Rx = torch.stack((o, z, z, z, cb, -sb, z, sb, cb), dim=1).reshape(n, 3, 3)
    Ry = torch.stack((ca, z, -sa, z, o, z, sa, z, ca), dim=1).reshape(n, 3, 3)   # Ry(-alpha)
    return Rz @ Rx @ Ry


class ShuttleGliderTrim:
    """Exact trimmed reset states for the merged Shuttle-Glider; all positions relative to the assembly CoM [m]."""

    def __init__(self, *, mass, gravity, rotor_positions, puller_position, reference_position, rotor_constant,
                 moment_constant, rot_dir, puller_constant, puller_moment_constant, puller_rot_dir, min_omega, max_omega,
                 aerodynamics, reserve: float = TRIM_ROTOR_RESERVE, iterations: int = 24, table: str = "limits",
                 device="cpu"):
        self.device = device
        self.table = TRIM_TABLES[table]
        f = lambda x: torch.as_tensor(x, dtype=torch.float32, device=device)
        self.m = float(mass)
        self.g = float(gravity)
        self.r_rotor = f(rotor_positions).reshape(4, 3)
        self.r_puller = f(puller_position).reshape(3)
        self.r_ref = f(reference_position).reshape(3)
        self.kf = f(rotor_constant).reshape(4)
        self.kq = f(moment_constant).reshape(4) * f(rot_dir).reshape(4)       # signed reaction torque per N^... * omega^2
        self.kf_p = float(puller_constant)
        self.kq_p = float(puller_moment_constant) * float(puller_rot_dir)
        self.min_w = f(min_omega).reshape(5)
        self.max_w = f(max_omega).reshape(5)
        self.G = aerodynamics.G
        self.C = aerodynamics.C
        self._cl_cd = aerodynamics.CL_CD
        self.reserve = float(reserve)
        self.iterations = int(iterations)
        # Rows: collective thrust, roll moment (y T), pitch moment (-x T), yaw reaction moment ((k_m/k_f) dir T)
        alloc = torch.stack((torch.ones(4, device=device), self.r_rotor[:, 1], -self.r_rotor[:, 0], self.kq / self.kf))
        self._alloc_inv = torch.linalg.inv(alloc)
        self.T_max = self.kf * self.max_w[:4].square()
        self.T_min = self.kf * self.min_w[:4].square()
        self.T_max_p = self.kf_p * float(self.max_w[4]) ** 2

    @classmethod
    def from_vehicle(cls, vehicle, gravity: float, device, reserve: float = TRIM_ROTOR_RESERVE, table: str = "limits"):
        """Read mass properties, actuator positions and propulsion constants of a ShuttleGliderBatch2."""
        from pegasus.simulator.logic.transforms import quaternion_apply

        masses = torch.as_tensor(vehicle._vehicle_prims.get_masses(), device=device).reshape(
            vehicle.n_vehicles, vehicle.parts_per_vehicle)[0]
        local_coms = vehicle._reset_part_positions_body + quaternion_apply(
            vehicle._reset_part_attitudes_body, vehicle._reset_part_coms)
        local_coms = local_coms[0].to(device)
        com = (local_coms * masses[:, None]).sum(0) / masses.sum()
        aero = vehicle.aerodynamics
        r_com = torch.as_tensor(aero.G.r_com, dtype=torch.float32, device=device)
        rotors = vehicle._rotor_positions_body[0].to(device) - com
        shuttle = vehicle._shuttle_thrusters
        puller = vehicle._glider_thruster
        thr = vehicle._thrusters
        return cls(mass=float(masses.sum()), gravity=gravity, rotor_positions=rotors[:4], puller_position=rotors[4],
                   reference_position=local_coms[vehicle.body_index] + r_com - com,
                   rotor_constant=shuttle._rotor_constant, moment_constant=shuttle._reaction_moment_coefficient,
                   rot_dir=shuttle._rot_dir.float(), puller_constant=float(puller._rotor_constant.reshape(-1)[0]),
                   puller_moment_constant=float(puller._reaction_moment_coefficient.reshape(-1)[0]),
                   puller_rot_dir=float(puller._rot_dir.reshape(-1)[0]), min_omega=thr.min_rotor_velocity.reshape(-1),
                   max_omega=thr.max_rotor_velocity.reshape(-1), aerodynamics=aero, reserve=reserve, table=table,
                   device=device)

    # ------------------------------------------------------------------
    def aero_wrench(self, speed, alpha, surfaces):
        """Aerodynamic force (FLU) and moment about the assembly CoM at beta = 0 and zero body rates.

        Same equations as GliderAerodynamicsBatch.forces_moments for that state; the reference point is the
        aerodynamic reference point relative to the assembly CoM."""
        G, C = self.G, self.C
        de, da, dr = surfaces.unbind(1)
        qS = 0.5 * G.rho * speed.square() * G.S
        CL, CD = self._cl_cd(alpha, de)
        lift = qS * (CL + C.CLde * de)
        drag = (qS * CD).clamp_min(0.0)
        ca, sa = torch.cos(alpha), torch.sin(alpha)
        F = torch.stack((-drag * ca + lift * sa, qS * (C.CY0 + C.CYda * da + C.CYdr * dr), drag * sa + lift * ca), dim=1)
        M = torch.stack((qS * G.b * (C.Cl0 + C.Clda * da + C.Cldr * dr),
                         qS * G.c * (C.Cm0 + C.Cma * alpha + C.Cmde * de),
                         qS * G.b * (C.Cn0 + C.Cnda * da + C.Cndr * dr)), dim=1)
        return F, M + torch.cross(self.r_ref.expand_as(F), F, dim=1)

    def _thrusts(self, speed, alpha, surfaces, weight):
        """Puller and lift-rotor thrusts closing the six equilibrium equations (lateral force excepted)."""
        F, M = self.aero_wrench(speed, alpha, surfaces)
        Tp = weight * torch.sin(alpha) - F[:, 0]
        collective = weight * torch.cos(alpha) - F[:, 2]
        # Moments of everything except the lift rotors: aerodynamics, puller thrust line and puller reaction torque
        Mx = M[:, 0] + self.kq_p / self.kf_p * Tp
        My = M[:, 1] + self.r_puller[2] * Tp
        Mz = M[:, 2] - self.r_puller[1] * Tp
        rhs = torch.stack((collective, -Mx, -My, -Mz), dim=1)
        T = rhs @ self._alloc_inv.T
        valid = ((Tp >= 0.0) & (Tp <= self.T_max_p)
                 & (T >= self.T_min + self.reserve - TRIM_THRUST_TOLERANCE).all(dim=1)
                 & (T <= self.T_max - self.reserve).all(dim=1))
        return Tp, T, valid

    def solve(self, speed: torch.Tensor, bank: torch.Tensor | None = None, use_surfaces: bool = False,
              alpha: torch.Tensor | None = None):
        """Trim at the given airspeeds [m/s] and bank angles [rad] (coordinated turn, negative = left wing down).

        Returns a dict with alpha [rad], surfaces [rad] (elevator, aileron, rudder), omega [rad/s] and rotor_norm in
        [-1, 1] for the five rotors, the thrusts and the residual-free state flag. ``alpha`` overrides the table."""
        speed = speed.to(dtype=torch.float32, device=self.device)
        n = speed.shape[0]
        bank = torch.zeros_like(speed) if bank is None else bank.to(dtype=torch.float32, device=self.device)
        weight = self.m * self.g / torch.cos(bank).clamp_min(0.2)
        alpha_req = torch.deg2rad(interpolate_table(speed, self.table["alpha"])) if alpha is None else alpha.to(speed)
        surfaces = torch.zeros((n, 3), dtype=torch.float32, device=self.device)
        if use_surfaces:
            for k, name in enumerate(("elevator", "aileron", "rudder")):
                surfaces[:, k] = torch.deg2rad(interpolate_table(speed, self.table[name]))

        ok = self._thrusts(speed, alpha_req, surfaces, weight)[2]
        if not torch.all(ok):
            # Reduce alpha towards zero until both thrust reserves hold (the alpha = 0 state must be feasible)
            low = torch.zeros_like(alpha_req)
            high = alpha_req.clone()
            if not torch.all(self._thrusts(speed, low, surfaces, weight)[2] | ok):
                raise RuntimeError("No admissible Shuttle-Glider trim at alpha = 0 for the requested speed and bank")
            for _ in range(self.iterations):
                mid = 0.5 * (low + high)
                good = self._thrusts(speed, mid, surfaces, weight)[2]
                low = torch.where(good, mid, low)
                high = torch.where(good, high, mid)
            alpha_req = torch.where(ok, alpha_req, low)
        Tp, T, valid = self._thrusts(speed, alpha_req, surfaces, weight)
        if not torch.all(valid):
            raise RuntimeError("Infeasible Shuttle-Glider trim; check the vehicle constants and the reserve")
        omega = torch.cat((torch.sqrt(T.clamp_min(0.0) / self.kf), torch.sqrt(Tp.clamp_min(0.0) / self.kf_p).unsqueeze(1)), dim=1)
        span = (self.max_w - self.min_w).clamp_min(1e-6)
        rotor_norm = 2.0 * (omega - self.min_w) / span - 1.0
        return dict(alpha=alpha_req, surfaces=surfaces, omega=omega, rotor_norm=rotor_norm, thrust=T, puller_thrust=Tp)
